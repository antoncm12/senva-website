def head(title, desc, path, og_title, og_desc, og_type='website', jsonld=None, root='', noindex=False, preload_sans=True):
    canonical = SITE + path
    html_cls = ' class="preview"' if PREVIEW else ''
    parts = ['<!doctype html>', f'<html lang="en-GB"{html_cls}>', '<head>', '<meta charset="utf-8">',
             '<meta name="viewport" content="width=device-width, initial-scale=1">',
             '<!-- Generated by _build/build_site.py: edit the content there, then rebuild. -->',
             f'<title>{esc(title)}</title>']
    if desc:
        parts.append(f'<meta name="description" content="{esc(desc)}">')
    if noindex or PREVIEW:
        parts.append('<meta name="robots" content="noindex">')
    if not noindex:
        parts += [
            f'<link rel="canonical" href="{canonical}">',
            '<meta property="og:site_name" content="Senva Health">', '<meta property="og:locale" content="en_GB">',
            f'<meta property="og:type" content="{og_type}">', f'<meta property="og:url" content="{canonical}">',
            f'<meta property="og:title" content="{esc(og_title)}">', f'<meta property="og:description" content="{esc(og_desc)}">',
            f'<meta property="og:image" content="{SITE}/og.png">', '<meta property="og:image:width" content="1200">',
            '<meta property="og:image:height" content="630">',
            '<meta property="og:image:alt" content="Senva Health: the at-home saliva test for your biological age. A spin-out from Umeå University.">',
            '<meta name="twitter:card" content="summary_large_image">',
        ]
    parts += [
        '<meta name="theme-color" content="#053033">',
        # Icons, all made from the Senva symbol. The ?v=2 and the new file names make browsers that cached the old icon
        # fetch the new one; keep these addresses from now on, since Google asks for a stable icon address. Google Search
        # reads ICO and PNG but not SVG, and recommends an icon larger than 48 px, hence the 192 px PNG.
        f'<link rel="icon" href="{root}favicon.ico?v=2" sizes="16x16 32x32 48x48">',
        f'<link rel="icon" href="{root}icon-192.png" type="image/png" sizes="192x192">',
        f'<link rel="icon" href="{root}icon.svg" type="image/svg+xml">',
        f'<link rel="apple-touch-icon" href="{root}apple-touch-icon.png">',
        f'<link rel="preload" href="{root}fonts/corben-400.woff2" as="font" type="font/woff2" crossorigin>',
    ]
    if preload_sans:
        parts.append(f'<link rel="preload" href="{root}fonts/ibm-plex-sans-300.woff2" as="font" type="font/woff2" crossorigin>')
    parts += [f'<link rel="stylesheet" href="{root}styles.css{ASSET_VERSION}">',
              "<script>document.documentElement.classList.add('js');</script>",
              f'<script src="{root}site.js{ASSET_VERSION}" defer></script>']
    if ANALYTICS_HEAD and not PREVIEW:
        parts.append(ANALYTICS_HEAD)
    if jsonld:
        parts.append('<script type="application/ld+json">\n' + json.dumps(jsonld, ensure_ascii=False, indent=1) + '\n</script>')
    parts.append('</head>')
    return '\n'.join(parts)


