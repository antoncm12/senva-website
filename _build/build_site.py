def ph(kind, title, text, media=False):
    """A box for a picture or fact still needed. Only in the preview build; empty on the live site."""
    if not PREVIEW:
        return ''
    cls = 'placeholder' + (' placeholder-media' if media else '')
    return f'<div class="{cls}"><strong>{kind} needed: {title}</strong>{text}</div>'


def ph_inline(text):
    return f' <span class="ph">{text}</span>' if PREVIEW else ''


