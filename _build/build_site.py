def faq_html():
    out = []
    for f in FAQ:
        if f.get('ph'):
            if PREVIEW:
                out.append(f'''        <details class="ph-item" open>
          <summary>{f["q"]}</summary>
          <p><span class="ph">{f["ph"]}</span></p>
        </details>''')
            continue
        extra = ph_inline(f['inline_ph']) if f.get('inline_ph') else ''
        opened = ' open' if extra else ''
        out.append(f'''        <details{opened}>
          <summary>{f["q"]}</summary>
          <p>{f["a"]}{f.get("more", "")}{extra}</p>
        </details>''')
    return '\n'.join(out)


