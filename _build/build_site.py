def page(name, head_html, main_html, root=''):
    banner = ('<div class="preview-banner" role="note">Preview of the content still needed. The dashed boxes are not on the live site; '
              'see CONTENT-NEEDED.md for the full list.</div>') if PREVIEW else ''
    body = [head_html, '<body>']
    if banner:
        body.append(banner)
    body += ['<a class="skip" href="#main">Skip to content</a>', '', header(name, root), '', main_html, '', footer(name, root), '</body>', '</html>', '']
    # drop lines left empty by placeholders in the live build
    return re.sub(r'(?m)^[ \t]+\n', '', '\n'.join(body))


